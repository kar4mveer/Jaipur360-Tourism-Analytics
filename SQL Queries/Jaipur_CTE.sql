Find hotels from the Luxury Hotels CTE that have above-average reviews.
--- CTE + SubQuery

WITH LUXURY_HOTELS AS
(SELECT HOTEL, PRICE_RUPEES, NUMBER_OF_REVIEWS
 FROM DBO.HOTELS
 WHERE PRICE_RUPEES >= 15000)
SELECT *
FROM LUXURY_HOTELS
WHERE NUMBER_OF_REVIEWS >
(SELECT AVG(NUMBER_OF_REVIEWS) FROM DBO.HOTELS);