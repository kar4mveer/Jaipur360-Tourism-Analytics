Count attractions by shift type.

SELECT
CASE
    WHEN IN_TIME2 = '-' THEN 'SINGLE SHIFT'
    ELSE 'MULTIPLE SHIFT'
END AS SHIFT_TYPE,
COUNT(*) AS TOTAL_ATTRACTIONS
FROM DBO.PLACES
GROUP BY
CASE
    WHEN IN_TIME2 = '-' THEN 'SINGLE SHIFT'
    ELSE 'MULTIPLE SHIFT'
END;

Count attractions by tourism type.

SELECT
CASE
    WHEN T.PRIORITY_1 = 'History and Culture' THEN 'Cultural Tourism'
    WHEN T.PRIORITY_1 = 'Museum' THEN 'Educational Tourism'
    WHEN T.PRIORITY_1 = 'Adventure' THEN 'Adventure Tourism'
    ELSE 'General Tourism'
END AS TOURISM_TYPE,
COUNT(*) AS TOTAL_ATTRACTIONS
FROM DBO.PLACES P
INNER JOIN DBO.TYPES T ON P.PID = T.PID
GROUP BY
CASE
    WHEN T.PRIORITY_1 = 'History and Culture' THEN 'Cultural Tourism'
    WHEN T.PRIORITY_1 = 'Museum' THEN 'Educational Tourism'
    WHEN T.PRIORITY_1 = 'Adventure' THEN 'Adventure Tourism'
ELSE 'General Tourism'
END
ORDER BY TOTAL_ATTRACTIONS DESC;

