Categorize hotels as Budget, Mid Range, Premium, or Luxury based on price.

SELECT HOTEL, PRICE_RUPEES,
CASE
WHEN PRICE_RUPEES < 2500 THEN 'BUDGET'
WHEN PRICE_RUPEES < 7000 THEN 'MID RANGE'
WHEN PRICE_RUPEES < 15000 THEN 'PREMIUM'
ELSE 'LUXURY'
END AS HOTEL_CATEGORY
FROM DBO.HOTELS;

Count hotels in each price category.

SELECT
        CASE
        WHEN PRICE_RUPEES < 2500 THEN 'BUDGET'
        WHEN PRICE_RUPEES < 7000 THEN 'MID RANGE'
        WHEN PRICE_RUPEES < 15000 THEN 'PREMIUM'
        ELSE 'LUXURY'
        END AS HOTEL_CATEGORY,
    COUNT(*) AS TOTAL_HOTELS
FROM DBO.HOTELS
GROUP BY 
        CASE
        WHEN PRICE_RUPEES < 2500 THEN 'BUDGET'
        WHEN PRICE_RUPEES < 7000 THEN 'MID RANGE'
        WHEN PRICE_RUPEES < 15000 THEN 'PREMIUM'
        ELSE 'LUXURY'
        END;

Categorize hotels based on popularity using review counts.

SELECT HOTEL, NUMBER_OF_REVIEWS,
CASE
    WHEN NUMBER_OF_REVIEWS >= 3000 THEN 'HIGHLY POPULAR'
    WHEN NUMBER_OF_REVIEWS >= 1000 THEN 'POPULAR'
    ELSE 'LESS POPULAR'
END AS POPULARITY
FROM DBO.HOTELS;

Count hotels in each popularity segment.

SELECT
CASE
    WHEN NUMBER_OF_REVIEWS >= 3000 THEN 'HIGHLY POPULAR'
    WHEN NUMBER_OF_REVIEWS >= 1000 THEN 'POPULAR'
ELSE 'LESS POPULAR'
END AS POPULARITY, COUNT(*) AS TOTAL_HOTELS
FROM DBO.HOTELS
GROUP BY
CASE
    WHEN NUMBER_OF_REVIEWS >= 3000 THEN 'HIGHLY POPULAR'
    WHEN NUMBER_OF_REVIEWS >= 1000 THEN 'POPULAR'
ELSE 'LESS POPULAR'
END;

